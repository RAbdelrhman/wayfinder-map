import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { writeFile, readFile } from 'node:fs/promises';

export async function exercise(page, base, label) {
  const preferences = label === 'desktop' ? '.shots/244/desktop-home/.wayfinder-map/settled.json' : '.shots/244/settled.json';
  await writeFile(preferences, '{}');
  await page.request.post(base + '/api/auth/switch', { data: { login: 'bob' } });
  await page.request.post(base + '/api/auth/switch', { data: { login: 'alice' } });
  const results = [];
  const mutations = [];
  page.on('request', request => { if (request.method() !== 'GET') mutations.push([request.method(), new URL(request.url()).pathname]); });
  page.setDefaultTimeout(10000);
  const shot = name => page.screenshot({ path: `.shots/244/${label}-${name}.png` });
  const visible = async selector => { await page.locator(selector).waitFor({ state: 'visible' }); };
  const noTour = async () => await page.locator('#tour-layer').waitFor({ state: 'hidden' });
  const replay = async () => {
    await page.goto(`${base}/settings`);
    await page.getByRole('link', { name: 'Help', exact: true }).click();
    await page.getByRole('button', { name: 'Take the tour', exact: true }).click();
    await visible('[data-tour-act="next"]');
  };
  await page.goto(base);
  await page.evaluate(() => localStorage.removeItem('wayfinder-map:tour'));
  await page.reload();
  await visible('[data-tour-act="not-now"]');
  await shot('invitation');
  await page.locator('[data-tour-act="not-now"]').click();
  await noTour();
  await page.reload();
  await noTour();
  assert.equal(await page.evaluate(() => localStorage.getItem('wayfinder-map:tour')), 'dismissed');
  results.push('First-launch invitation, Not now, and reload suppression passed');
  await page.evaluate(() => localStorage.removeItem('wayfinder-map:tour'));
  await page.reload();
  await page.locator('[data-tour-act="take-tour"]').click();
  await visible('[data-tour-act="next"]');
  await page.locator('[data-tour-act="exit"]').click();
  await noTour();
  results.push('Accepting the first-launch invitation starts step one and exits cleanly');
  await replay();
  await page.locator('[data-tour-act="exit"]').click();
  await noTour();
  results.push('Settings Help replay and exit passed');
  await replay();
  const tourStart = mutations.length;
  const next = () => page.locator('#tour-layer [data-tour-act="next"]').click();
  await next();
  await page.locator('#demo-start').click();
  await page.locator('#demo-open-map').click();
  await next();
  await next();
  await page.locator('#tour-layer [data-ticket="6"]').click();
  await next();
  await page.locator('#tour-layer [data-ticket="5"]').click();
  await page.locator('#demo-open').click();
  await next();
  await visible('.tour-done-icon');
  await shot('completion');
  assert.equal(await page.evaluate(() => localStorage.getItem('wayfinder-map:tour')), 'completed');
  assert.deepEqual(mutations.slice(tourStart), [], 'Tour must not submit any real API mutations');
  await page.locator('[data-tour-act="exit"]').click();
  await noTour();
  await page.goto(base);
  await noTour();
  await replay();
  await page.keyboard.press('Escape');
  await noTour();
  results.push('Full planning, blocked ticket, ready ticket, simulated hand-off, completion, replay after completion, Escape passed; zero HTTP mutations during demo');
  await page.goto(`${base}/repos/fixture/tutorial`);
  await page.getByRole('button', { name: /^Archive map #/ }).waitFor();
  await shot('active');
  await page.getByRole('button', { name: /^Archive map #/ }).click();
  await page.getByText('Every map here is archived.', { exact: true }).waitFor();
  await page.getByRole('link', { name: /Archived maps/ }).first().click();
  await page.getByText('Archived by you', { exact: true }).first().waitFor();
  await shot('archived');
  const beforeOpen = JSON.parse(await readFile(label === 'desktop' ? '.shots/244/desktop-home/.wayfinder-map/settled.json' : '.shots/244/settled.json', 'utf8'));
  await page.getByRole('link', { name: /^Open map #/ }).click();
  await page.getByRole('button', { name: /^Restore map #/ }).waitFor();
  assert.deepEqual(JSON.parse(await readFile(label === 'desktop' ? '.shots/244/desktop-home/.wayfinder-map/settled.json' : '.shots/244/settled.json', 'utf8')), beforeOpen, 'Opening an archive must not alter preferences');
  await shot('opened-archive');
  await page.getByRole('button', { name: /^Restore map #/ }).click();
  await page.goto(`${base}/repos/fixture/tutorial`);
  await page.getByRole('button', { name: /^Archive map #/ }).waitFor();
  results.push('Manual Archive, archived-map Open with unchanged disk preferences, and Restore passed');
  await page.getByRole('link', { name: /Archived maps/ }).first().click();
  await page.getByText('Finished', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: /^Restore map #/ }).click();
  await page.goto(`${base}/repos/fixture/tutorial`);
  await page.getByText('#20 Finished verification map', { exact: true }).first().waitFor();
  await page.reload();
  await page.getByText('#20 Finished verification map', { exact: true }).first().waitFor();
  results.push('Automatic Finished archive and persistent Restore override passed');
  await page.getByRole('option', { name: '#10 Active verification map', exact: true }).click();
  await page.getByRole('button', { name: /^Archive map #/ }).click();
  await page.getByText('#20 Finished verification map', { exact: true }).first().waitFor();
  await shot('alice');
  await page.goto(`${base}/settings`);
  await page.getByRole('link', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'bob', exact: true }).click();
  await page.getByRole('button', { name: 'alice', exact: true }).waitFor();
  await page.goto(`${base}/repos/fixture/tutorial`);
  await page.getByRole('option', { name: '#10 Active verification map', exact: true }).waitFor();
  assert.equal(await page.getByRole('option', { name: '#20 Finished verification map', exact: true }).count(), 0);
  await shot('bob');
  await page.getByRole('link', { name: /Archived maps/ }).first().click();
  await page.getByRole('option', { name: '#20 Finished verification map', exact: true }).waitFor();
  assert.equal(await page.getByRole('option', { name: '#10 Active verification map', exact: true }).count(), 0);
  await page.goto(`${base}/settings?section=account`);
  await page.getByRole('button', { name: 'alice', exact: true }).click();
  await page.getByRole('button', { name: 'bob', exact: true }).waitFor();
  await page.goto(`${base}/repos/fixture/tutorial`);
  await page.getByRole('option', { name: '#20 Finished verification map', exact: true }).waitFor();
  assert.equal(await page.getByRole('option', { name: '#10 Active verification map', exact: true }).count(), 0);
  results.push('Settings account switch Alice to Bob to Alice preserved Alice manual archive and finished Restore override, with neither leaking to Bob');
  await shot('alice-return');
  await page.getByRole('link', { name: /Archived maps/ }).first().click();
  await page.getByRole('option', { name: '#10 Active verification map', exact: true }).waitFor();
  await page.getByText('Archived by you', { exact: true }).first().waitFor();
  assert.equal(await page.getByRole('option', { name: '#20 Finished verification map', exact: true }).count(), 0);
  await writeFile(`.shots/244/${label}-results.json`, JSON.stringify({ results, mutations }, null, 2));
  return { results, mutations, shot };
}

if (process.argv[1].endsWith('flow.mjs')) {
  const browser = await chromium.launch({ channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  try { await exercise(page, 'http://127.0.0.1:4484', 'browser'); }
  catch (error) { console.error(error); console.log(await page.locator('body').innerText()); await page.screenshot({ path: '.shots/244/failure.png' }); process.exitCode = 1; }
  finally { await browser.close(); }
}
